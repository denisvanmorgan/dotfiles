return {
  "goolord/alpha-nvim",
  dependencies = { "nvim-tree/nvim-web-devicons" },
  config = function()
    local dashboard = require("alpha.themes.dashboard")

    local header = {
      type = "text",
      val = logo,
      opts = {
        position = "center",
        hl       = "Whitespace",
        wrap     = "overflow"
      },
    }

    local footer = {
      type = "text",
      val = {
        "You suffer, but why?",
      },
      opts = {
        position = "center",
        hl       = "Whitespace",
      }
    }

    local buttons = {
      type = "group",
      val = {
        dashboard.button("e", "  New Buffer",            "<cmd>tabnew<CR>"),
        dashboard.button("f", "  Find file",             "<cmd>Telescope find_files<CR>"),
        dashboard.button("h", "  Recently opened files", "<cmd>Telescope oldfiles<CR>"),
        dashboard.button("l", "  Projects",              "<cmd>Telescope project<CR>"),
        dashboard.button("m", "  Word Finder",           "<cmd>Telescope live_grep<CR>"),
      },
      opts = {
        spacing = 1,
      }
    }

    --
    -- Centering handler of ALPHA (evaluated on every redraw, so it follows resizes)
    --

    local padding_between = 3

    local function occupied(with_logo)
      -- buttons + spacing, footer, 2 lines for cmdline/statusline
      return (with_logo and #logo + padding_between or 0) + #buttons.val * 2 - 1 + #footer.val + 2
    end

    local function logo_fits()
      return vim.o.lines >= occupied(true)
    end

    header.val = function()
      return logo_fits() and logo or {}
    end

    require("alpha").setup({
      layout = {
        { type = "padding", val = function() return math.max(0, math.floor((vim.o.lines - occupied(logo_fits())) / 2)) end },
        header,
        { type = "padding", val = function() return logo_fits() and padding_between or 0 end },
        buttons,
        footer,
      },
      opts = {
        margin = 5
      },
    })
  end,
}
